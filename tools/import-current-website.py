#!/usr/bin/env python3
"""Import a pinned website checkout without rewriting its educational content."""
import hashlib
import json
import mimetypes
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MINI = ROOT / 'miniprogram'
SOURCE = Path(sys.argv[1]).resolve()
source_text = (SOURCE / 'course-index.js').read_text()
offset = source_text.index('window.COURSE = ') + len('window.COURSE = ')
index, _ = json.JSONDecoder().raw_decode(source_text[offset:])
commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=SOURCE, text=True).strip()

def dump(file, value, pretty=False):
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(json.dumps(value, ensure_ascii=False, indent=2 if pretty else None,
                               separators=None if pretty else (',', ':')) + '\n')

def module(file, value):
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text('// Generated from the pinned website source; do not rewrite course facts here.\nmodule.exports = ' + json.dumps(value, ensure_ascii=False, separators=(',', ':')) + ';\n')

def stub(folder):
    dest = MINI / folder / 'stub'
    dest.mkdir(parents=True, exist_ok=True)
    (dest / 'index.js').write_text('Page({ onLoad() { wx.navigateBack(); } });\n')
    (dest / 'index.json').write_text('{"navigationBarTitleText":"学习资源"}\n')
    (dest / 'index.wxml').write_text('<view>学习资源按需加载</view>\n')
    (dest / 'index.wxss').write_text('page{padding:40rpx}\n')

# These directories were generated by the earlier migration, not by the user.
for folder in MINI.iterdir():
    if folder.is_dir() and (folder.name.startswith('media') or folder.name.startswith('unitdata')):
        shutil.rmtree(folder)
for folder in [MINI / 'data', ROOT / 'audio-resources', ROOT / 'course-sources']:
    if folder.exists():
        shutil.rmtree(folder)
(MINI / 'data/vocabulary').mkdir(parents=True, exist_ok=True)

course = {'title': index['title'], 'version': '2026.10.30', 'totalLists': index['totalLists'],
          'sourceCommit': commit, 'lists': {}, 'unitFiles': {}}
all_audio = set()
source_audit = []
learning_cards = {}
first_unit_audio = set()
data_package = 1
data_bytes = 0

for number in sorted(map(int, index['unitFiles'])):
    source_path = index['unitFiles'][str(number)]
    raw = (SOURCE / source_path).read_bytes()
    bundle = json.loads(raw)
    assert bundle['number'] == number
    assert len(bundle['unit']['vocabulary']) == len(bundle['unit']['examples']) == 15
    if data_bytes + len(raw) > 1_400_000:
        data_package += 1
        data_bytes = 0
    package = 'unitdata' + str(data_package)
    # .json is reserved for mini-program compiler configuration. Keep the
    # source bytes intact as an explicitly included, readable text resource.
    relative = f'{package}/units/unit-{number:03d}.txt'
    target = MINI / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(raw)
    data_bytes += len(raw)
    course['unitFiles'][str(number)] = {'package': package, 'path': relative,
        'sourcePath': source_path, 'sha256': hashlib.sha256(raw).hexdigest()}
    words = []
    for i, word in enumerate(bundle['unit']['vocabulary']):
        identity = '|'.join([word['word'].lower().replace('’', "'"), word['ipa'], word['partsOfSpeech'], word['meaning']])
        word_id = 'word:' + hashlib.sha256(identity.encode()).hexdigest()[:20]
        key = word['word'].lower().replace('’', "'")
        audio = bundle['dictionary'].get(key, {}).get('audio', '')
        assert audio and (SOURCE / audio).is_file(), (number, word['word'])
        entry = {**word, 'id': word_id, 'listId': number, 'exampleIndex': i, 'audio': audio}
        words.append(entry)
        if word_id not in learning_cards:
            learning_cards[word_id] = {'id': word_id, 'word': word['word'], 'listId': number, 'listIds': []}
        learning_cards[word_id]['listIds'].append(number)
    module(MINI / f'data/vocabulary/unit-{number:03d}.js', words)
    course['lists'][str(number)] = {'id': number, 'title': 'Unit ' + str(number)}
    used = {x['audio'] for x in bundle['dictionary'].values() if x.get('audio')}
    used |= {x['audio'] for x in bundle['unit']['examples'] if x.get('audio')}
    all_audio |= used
    if number == 1:
        first_unit_audio = used
    source_audit.append({'unit': number, 'sourcePath': source_path, 'runtimePath': relative,
                         'sha256': hashlib.sha256(raw).hexdigest(), 'vocabulary': len(words),
                         'examples': len(bundle['unit']['examples']), 'dictionaryEntries': len(bundle['dictionary'])})

catalog_js = '// Generated vocabulary index. Individual lesson content loads from resource subpackages.\n'
catalog_js += 'const course = ' + json.dumps(course, ensure_ascii=False, separators=(',', ':')) + ';\n'
for number in sorted(map(int, course['lists'])):
    catalog_js += f"course.lists[{number}].vocabulary = require('./vocabulary/unit-{number:03d}');\n"
catalog_js += 'module.exports = course;\n'
(MINI / 'data/course.js').write_text(catalog_js)

audio_manifest = []
for source_path in sorted(all_audio):
    source = SOURCE / source_path
    assert source.is_file(), source_path
    raw = source.read_bytes()
    target = ROOT / 'audio-resources' / source_path
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    audio_manifest.append({'path': source_path, 'bytes': len(raw),
        'sha256': hashlib.sha256(raw).hexdigest(),
        'gitBlobSha': hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest(),
        'mime': mimetypes.guess_type(source_path)[0] or 'application/octet-stream'})

demo_manifest = {}
audio_package = 1
audio_bytes = 0
for source_path in sorted(first_unit_audio):
    raw = (SOURCE / source_path).read_bytes()
    if audio_bytes + len(raw) > 1_400_000:
        audio_package += 1
        audio_bytes = 0
    digest = hashlib.sha256(raw).hexdigest()
    ext = Path(source_path).suffix
    package = 'media' + str(audio_package)
    relative = f'{package}/files/{digest[:24]}{ext}'
    target = MINI / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(raw)
    demo_manifest[source_path] = {'package': package, 'path': relative, 'hash': digest[:24],
                                  'bytes': len(raw), 'extension': ext}
    audio_bytes += len(raw)
module(MINI / 'data/audio-manifest.js', demo_manifest)
module(MINI / 'data/notices.js', [])
dump(ROOT / 'course-sources/unit-provenance.json', source_audit, True)
dump(ROOT / 'audio-resource-manifest.json', {'sourceCommit': commit, 'files': audio_manifest}, True)
for name in ['course-units1-120.json', 'preserved-units1-32.json', 'youdao-course.json']:
    shutil.copyfile(SOURCE / 'data' / name, ROOT / 'course-sources' / name)
shutil.copyfile(SOURCE / 'audio/course-examples/manifest.json', ROOT / 'course-sources/sentence-audio-manifest.json')
shutil.copyfile(SOURCE / 'README.md', ROOT / 'course-sources/website-readme.md')

app = json.loads((MINI / 'app.json').read_text())
app['subpackages'] = []
for prefix, count in [('unitdata', data_package), ('media', audio_package)]:
    for number in range(1, count + 1):
        name = prefix + str(number)
        stub(name)
        app['subpackages'].append({'name': name, 'root': name, 'pages': ['stub/index']})
dump(MINI / 'app.json', app, True)
project = json.loads((ROOT / 'project.config.json').read_text())
pack = project.setdefault('packOptions', {})
includes = [x for x in pack.get('include', []) if not x.get('value', '').startswith('unitdata')]
includes += [{'type': 'folder', 'value': f'unitdata{n}/units'} for n in range(1, data_package + 1)]
pack['include'] = includes
dump(ROOT / 'project.config.json', project, True)
dump(ROOT / 'cloudfunctions/learning/catalog.json', {'words': list(learning_cards.values()), 'listIds': sorted(map(int, course['lists']))})
dump(ROOT / 'SOURCE.json', {'repository': 'https://github.com/FitzLeewenlei/English-learning',
    'website': 'https://fitzleewenlei.github.io/English-learning/', 'commit': commit,
    'units': len(course['lists']), 'vocabularyEntries': 1800, 'examples': 1800,
    'learningCards': len(learning_cards), 'audioFiles': len(audio_manifest),
    'audioBytes': sum(a['bytes'] for a in audio_manifest),
    'dataPackages': data_package, 'demoAudioPackages': audio_package}, True)
from PIL import Image
logo = Image.open(SOURCE / 'assets/haina-emblem.webp').convert('RGBA')
logo.thumbnail((144, 144))
logo.save(MINI / 'assets/logo.png', optimize=True)
subprocess.run([sys.executable, str(ROOT / 'tools/organize-audio.py')], check=True)
print((ROOT / 'SOURCE.json').read_text())
